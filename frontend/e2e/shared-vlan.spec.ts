import {test,expect} from '@playwright/test';
const network=(page:any,id:string)=>page.locator('.diagram .network-group[data-network-kind="vlan"][data-network-id="'+id+'"]');
const row=(page:any,id:string)=>page.locator('.diagram [data-layer="l2"] .interface-row[data-element-id="'+id+'"]');
test('one shared VLAN frame connects devices and trunks; click persists membership highlight',async({page})=>{
 await page.goto('/');await expect(page.getByLabel('検証結果')).toContainText('検証済み');
 await page.getByRole('tab',{name:'L2 VLAN',exact:true}).click();
 await expect(page.locator('.diagram [data-layer]')).toHaveCount(1);await expect(page.getByLabel('検証結果')).toContainText('検証済み');
 await expect(page.locator('.diagram .vlan-frame')).toHaveCount(2);
 const office=network(page,'vlan-office'),guest=network(page,'vlan-guest');
 await expect(office.locator('.relation-branch')).toHaveCount(4);
 await expect(guest.locator('.relation-branch')).toHaveCount(4);
 for(const id of ['pc-a.l2','sw01.access1','sw01.trunk','gw01.trunk'])await expect(office.locator('.relation-branch[data-endpoint="'+id+'"]')).toHaveCount(1);
 await office.focus();await page.keyboard.press('Enter');await expect(office).toHaveAttribute('aria-pressed','true');
 await page.mouse.move(1,1);
 await expect.poll(()=>row(page,'pc-a.l2').evaluate(e=>getComputedStyle(e).opacity)).toBe('1');
 await expect.poll(()=>row(page,'pc-b.l2').evaluate(e=>getComputedStyle(e).opacity)).toBe('0.22');
 await expect.poll(()=>office.locator('.vlan-frame').evaluate(e=>getComputedStyle(e).strokeWidth)).toBe('3px');
 await expect.poll(()=>office.locator('.relation-branch').first().evaluate(e=>getComputedStyle(e).strokeWidth)).toBe('3px');
 await expect(page.getByLabel('図面とYAMLの対応',{exact:true})).toContainText('l2.vlans / vlan-office');
 await page.screenshot({path:(process.env.QA_ARTIFACTS||'test-results')+'/shared-vlan-selected.png',fullPage:true});
 await guest.focus();await page.keyboard.press('Space');await expect(guest).toHaveAttribute('aria-pressed','true');await expect(office).toHaveAttribute('aria-pressed','false');
 await expect.poll(()=>row(page,'pc-a.l2').evaluate(e=>getComputedStyle(e).opacity)).toBe('0.22');
 await expect.poll(()=>row(page,'sw01.trunk').evaluate(e=>getComputedStyle(e).opacity)).toBe('1');
 await page.keyboard.press('Escape');await expect(guest).toHaveAttribute('aria-pressed','false');
 await office.getByText('V1 / vlan-office / VLAN 10 / 業務LAN',{exact:true}).click();await expect(office).toHaveAttribute('aria-pressed','true');await expect(office).toBeFocused();
 await page.keyboard.press('Escape');await expect(office).toHaveAttribute('aria-pressed','false');
 await row(page,'sw01.trunk').focus();await page.keyboard.press('Enter');
 await expect(page.locator('.diagram [data-layer]')).toHaveCount(3);
 await expect(page.getByLabel('層間対応の追跡')).toContainText('sw01.trunk');
 await expect(page.getByLabel('層間対応の追跡')).toContainText('sw01.p24');
});
test('equal VLAN numbers keep separate frames and filtering preserves only visible memberships',async({page,request})=>{
 await page.goto('/');await expect(page.getByLabel('検証結果')).toContainText('検証済み');
 const source=(await(await request.get('/api/sample')).json()).yaml_text;
 await page.getByRole('textbox',{name:'YAMLエディター'}).fill(source.replace('tag: 20','tag: 10'));
 await expect(page.getByLabel('検証結果')).toContainText('検証済み');
 await expect(page.locator('.diagram .vlan-frame')).toHaveCount(2);
 await expect(network(page,'vlan-office')).toHaveCount(1);await expect(network(page,'vlan-guest')).toHaveCount(1);
 await page.getByLabel('表示する機器',{exact:true}).selectOption('gw01');
 await expect(page.locator('.diagram .device-card')).toHaveCount(3);
 await expect(page.locator('.diagram .vlan-frame')).toHaveCount(2);
 await expect(network(page,'vlan-office').locator('.relation-branch')).toHaveCount(1);
 await expect(network(page,'vlan-guest').locator('.relation-branch')).toHaveCount(1);
 await network(page,'vlan-office').focus();await page.keyboard.press('Enter');
 await expect(page.getByLabel('図面とYAMLの対応',{exact:true})).toContainText('l2.vlans / vlan-office');
});
